/**
 * Adopts the UIScene life cycle on iOS.
 *
 * iOS 27 kills any app that has not adopted scenes, at launch, before a line of
 * JS runs (`_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`).
 * Expo's SDK 57 template still starts React Native from the AppDelegate, so a
 * TestFlight build crashed on every iOS 27 phone while the iOS 26 simulator ran
 * it fine.
 *
 * SDK 58 fixes this upstream with `ExpoAppSceneDelegate`, which SDK 57 does not
 * ship. This plugin backports it: a SceneDelegate that creates the window and
 * starts React Native, a scene manifest in Info.plist, and an AppDelegate that
 * no longer builds a window of its own. `/ios` is generated, so this has to be a
 * plugin — a hand edit is gone at the next prebuild.
 *
 * Delete this plugin when moving to SDK 58; its template does all of this.
 */
const fs = require('fs');
const path = require('path');
const {
    IOSConfig,
    withAppDelegate,
    withInfoPlist,
    withXcodeProject,
} = require('expo/config-plugins');

const SCENE_DELEGATE = `// Generated by plugins/with-ios-scene-lifecycle.js — edit it there, not here.
//
// A backport of SDK 58's ExpoAppSceneDelegate. iOS 27 refuses to launch an app
// that has not adopted the scene life cycle.

import UIKit
import React
internal import Expo

@objc(SceneDelegate)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: AppDelegate? {
    UIApplication.shared.delegate as? AppDelegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else {
      return
    }
    guard let appDelegate, let factory = appDelegate.reactNativeFactory else {
      fatalError("SceneDelegate: AppDelegate did not create its React Native factory.")
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // Code that reads UIApplication.shared.delegate?.window (expo-system-ui)
    // still finds it.
    appDelegate.window = window

    // Under scenes a cold-start link arrives in connectionOptions, but
    // Linking.getInitialURL() only reads launch options — rebuild them.
    let browsingWebActivity = connectionOptions.userActivities.first {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: Self.launchOptions(
        url: connectionOptions.urlContexts.first?.url,
        userActivity: browsingWebActivity
      )
    )

    connectionOptions.urlContexts.forEach { open($0) }
    connectionOptions.userActivities.forEach { continueActivity($0) }
    if let shortcutItem = connectionOptions.shortcutItem {
      appDelegate.application(UIApplication.shared, performActionFor: shortcutItem) { _ in }
    }
  }

  func sceneDidDisconnect(_ scene: UIScene) {
    window = nil
  }

  // UIKit stops calling the app delegate's life-cycle, URL and activity
  // methods under scenes. Re-feed them: ExpoAppDelegate forwards each one to its
  // subscribers, and AppDelegate's overrides pass links to RCTLinkingManager.

  func sceneDidBecomeActive(_ scene: UIScene) {
    appDelegate?.applicationDidBecomeActive(UIApplication.shared)
  }

  func sceneWillResignActive(_ scene: UIScene) {
    appDelegate?.applicationWillResignActive(UIApplication.shared)
  }

  func sceneWillEnterForeground(_ scene: UIScene) {
    appDelegate?.applicationWillEnterForeground(UIApplication.shared)
  }

  func sceneDidEnterBackground(_ scene: UIScene) {
    appDelegate?.applicationDidEnterBackground(UIApplication.shared)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    URLContexts.forEach { open($0) }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    continueActivity(userActivity)
  }

  func windowScene(
    _ windowScene: UIWindowScene,
    performActionFor shortcutItem: UIApplicationShortcutItem,
    completionHandler: @escaping (Bool) -> Void
  ) {
    guard let appDelegate else {
      completionHandler(false)
      return
    }
    appDelegate.application(
      UIApplication.shared,
      performActionFor: shortcutItem,
      completionHandler: completionHandler
    )
  }

  private func open(_ context: UIOpenURLContext) {
    var options: [UIApplication.OpenURLOptionsKey: Any] = [
      .openInPlace: context.options.openInPlace,
    ]
    if let sourceApplication = context.options.sourceApplication {
      options[.sourceApplication] = sourceApplication
    }
    if let annotation = context.options.annotation {
      options[.annotation] = annotation
    }
    _ = appDelegate?.application(UIApplication.shared, open: context.url, options: options)
  }

  private func continueActivity(_ userActivity: NSUserActivity) {
    _ = appDelegate?.application(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in }
    )
  }

  /// The launch options Linking.getInitialURL() reads, or nil when the app was
  /// not cold-started by a link. Keys are spelled out because the UIApplication
  /// accessors are deprecated in iOS 26 — React Native still reads these names.
  private static func launchOptions(
    url: URL?,
    userActivity: NSUserActivity?
  ) -> [UIApplication.LaunchOptionsKey: Any]? {
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url {
      launchOptions[UIApplication.LaunchOptionsKey(rawValue: "UIApplicationLaunchOptionsURLKey")] = url
    }
    if let userActivity {
      launchOptions[UIApplication.LaunchOptionsKey(
        rawValue: "UIApplicationLaunchOptionsUserActivityDictionaryKey"
      )] = [
        "UIApplicationLaunchOptionsUserActivityTypeKey": userActivity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": userActivity,
      ]
    }
    return launchOptions.isEmpty ? nil : launchOptions
  }
}
`;

// The SDK 57 AppDelegate's window setup. SceneDelegate does this now; left in
// place, it would start React Native a second time into an orphan window.
const APP_DELEGATE_WINDOW = /\n#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\([\s\S]*?\)\n#endif\n/;
const APP_DELEGATE_MARKER = '// The window is created and React Native started by SceneDelegate';

function withSceneManifest(config) {
    return withInfoPlist(config, (config) => {
        config.modResults.UIApplicationSceneManifest = {
            UIApplicationSupportsMultipleScenes: false,
            UISceneConfigurations: {
                UIWindowSceneSessionRoleApplication: [
                    {
                        UISceneConfigurationName: 'Default Configuration',
                        UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
                    },
                ],
            },
        };
        return config;
    });
}

function withoutAppDelegateWindow(config) {
    return withAppDelegate(config, (config) => {
        const { contents, language } = config.modResults;
        if (language !== 'swift') {
            throw new Error('with-ios-scene-lifecycle: expected a Swift AppDelegate.');
        }
        if (contents.includes(APP_DELEGATE_MARKER)) return config;
        if (!APP_DELEGATE_WINDOW.test(contents)) {
            // Fail the prebuild rather than ship a second React Native start.
            throw new Error(
                'with-ios-scene-lifecycle: the AppDelegate window setup has changed shape. ' +
                    'If this is SDK 58 or later, delete this plugin.',
            );
        }
        config.modResults.contents = contents.replace(
            APP_DELEGATE_WINDOW,
            `\n    ${APP_DELEGATE_MARKER}\n    // under the scene life cycle, which iOS 27 requires.\n`,
        );
        return config;
    });
}

function withSceneDelegateFile(config) {
    return withXcodeProject(config, (config) => {
        const projectName = config.modRequest.projectName;
        const file = path.join(config.modRequest.platformProjectRoot, projectName, 'SceneDelegate.swift');
        fs.writeFileSync(file, SCENE_DELEGATE);

        const filepath = `${projectName}/SceneDelegate.swift`;
        if (!config.modResults.hasFile(filepath)) {
            IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
                filepath,
                groupName: projectName,
                project: config.modResults,
            });
        }
        return config;
    });
}

module.exports = function withIosSceneLifecycle(config) {
    return withSceneDelegateFile(withoutAppDelegateWindow(withSceneManifest(config)));
};
